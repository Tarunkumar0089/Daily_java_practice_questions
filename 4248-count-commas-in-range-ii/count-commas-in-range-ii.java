class Solution {
    public long countCommas(long n) {
        // 1000-999,999 -> x*1 
        // 1,000,000 - 999,999,999 ->x*2
        // 1,000,000,000 - 999,999,999,999 -> x*3
        // 1,000,000,000,000 - 999,999,999,999,999 -> x*4
        // 1,000,000,000,000,000 -> 5
        // 1,000,000, 000, 000, 000 ->5 
        // Q -> 767,987,456
        // HashMap<Long,Long> map = new HashMap<>();
        // map.put(1000-999999);
        // map.put(1000000 , 999999999);
        // map.put(1000000000 , 999999999999);
        // map.put(1000000000000 , 999999999999999);
        long ans=0;
        long num=1000L;
        while(n>=num){
            ans+=(n-num+1);

            num*=1000;
        }
        return ans;
    }
}